function inject(langObjStr, map) {
  let inner = langObjStr;
  for (const [k, v] of Object.entries(map)) {
    if (!inner.includes(`\n    ${k}:`)) {
      inner = inner.replace(/\n  \}/, `,\n    ${k}: ${JSON.stringify(v)}\n  }`);
    } else {
      let r = new RegExp(`^(\\s*${k}:\\s*")[^"]*(")`, "m");
      inner = inner.replace(r, `$1${v}$2`);
    }
  }
  return inner;
}

const blocks = content.split(/(?=\b(?:en|ta|si):\s*\{)/);

let final = blocks[0];
for (let i = 1; i < blocks.length; i++) {
  if (blocks[i].startsWith("ta:")) {
    final += inject(blocks[i], taReplacements);
  } else if (blocks[i].startsWith("en:")) {
    final += inject(blocks[i], enReplacements);
  } else if (blocks[i].startsWith("si:")) {
    final += inject(blocks[i], Object.fromEntries(Object.keys(enReplacements).map(k => [k, enReplacements[k]]))); // fallback to EN for missing SI
  } else {
    final += blocks[i];
  }
}

fs.writeFileSync("src/lib/i18n/translations.ts", final, "utf8");

